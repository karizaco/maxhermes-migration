#!/usr/bin/env python3
"""
test_preopen_checkpoint_contract.py — prove the checker actually CATCHES breaches.

A checker that has only ever been seen passing is a CLAIM, not a guard. This file
renders a CONFORMING artifact set (which must PASS), then mutates it one thing at a
time (each of which must FAIL). Every mutation's text actually changes — a mutation
that does not alter the file reports a false "NOT CAUGHT" and hides a dead check.

USAGE
    python3 test_preopen_checkpoint_contract.py [--repo <repo-root>]

EXIT CODES
  0 = every conforming case passed and every breach was caught
  1 = at least one case failed
"""

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

REPO = os.path.abspath(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CHECKER = os.path.join(REPO, "tools", "check_preopen_checkpoint.py")
SCRIPT = os.path.join(REPO, "cloud-prompts", "_shared", "preopen_checkpoint.py")

RESULTS = []


def run_checker(repo, tape=None, digest=None, skipped=None, slot="0830"):
    cmd = [sys.executable, CHECKER, "--repo", repo, "--slot", slot]
    if tape:
        cmd += ["--tape", tape]
    if digest:
        cmd += ["--digest", digest]
    if skipped:
        cmd += ["--skipped", skipped]
    r = subprocess.run(cmd, capture_output=True, text=True)
    return r.returncode, r.stdout


def record(name, expect_pass, rc, out):
    ok = (rc == 0) if expect_pass else (rc != 0)
    RESULTS.append((name, ok, rc, out))
    tag = "PASS" if ok else "FAIL"
    print(f"  {tag}  {name}  (checker exit {rc}, expected {'0' if expect_pass else 'non-zero'})")
    if not ok:
        for line in out.splitlines():
            if line.strip().startswith("FAIL"):
                print(f"        {line.strip()}")
    return ok


def make_repo(dst, src=REPO):
    """A writable copy of the three files the checker reads."""
    os.makedirs(os.path.join(dst, "cloud-prompts", "_shared"), exist_ok=True)
    os.makedirs(os.path.join(dst, "cloud-prompts", "cron-prompts"), exist_ok=True)
    for rel in ("cloud-prompts/_shared/preopen-capture.md",
                "cloud-prompts/_shared/preopen_checkpoint.py",
                "cloud-prompts/cron-prompts/92a-preopen-catalyst-capture-0830.md",
                "cloud-prompts/cron-prompts/92b-preopen-catalyst-capture-0950.md"):
        shutil.copy(os.path.join(src, rel), os.path.join(dst, rel))
    return dst


def build_conforming(tmp, n_rows=400):
    """A real tape + digest, generated by the real script from a synthetic snapshot."""
    work = os.path.join(tmp, "work")
    os.makedirs(work, exist_ok=True)
    gain, loss, grok = [], [], []
    for i in range(n_rows):
        t = f"T{i:04d}"
        pct = round(60.0 - i * 0.1, 2) if i % 2 == 0 else round(-(60.0 - i * 0.1), 2)
        d = [t, f"{t} Inc", None, None, None, None, None, pct, None, 10.0, None, "NASDAQ"]
        (gain if pct > 0 else loss).append({"s": "NASDAQ", "d": d})
    grok.append({"ticker": "T0000", "name": "T0000 Inc", "pct": 999.0, "cat": "earnings",
                 "why": "beat and raised | confirmed", "ref": "https://example.com/x",
                 "conf": "high"})
    json.dump({"data": gain}, open(os.path.join(work, "tv_gain.json"), "w"))
    json.dump({"data": loss}, open(os.path.join(work, "tv_loss.json"), "w"))
    with open(os.path.join(work, "grok.txt"), "w") as fh:
        fh.write(json.dumps(grok[0]) + "\n")
    json.dump({"model": "grok-4.3", "cost_usd": 0.0476, "web_search_calls": 3,
               "x_search_calls": 1, "input_tokens": 25110, "output_tokens": 2043},
              open(os.path.join(work, "meta.json"), "w"))

    feed = os.path.join(tmp, "preopen-feed")
    os.makedirs(feed, exist_ok=True)
    tape = os.path.join(feed, "2026-11-06-0830.jsonl")
    digest = os.path.join(feed, "2026-11-06-0830.md")
    subprocess.run([sys.executable, SCRIPT, "merge",
                    "--grok-reply", os.path.join(work, "grok.txt"),
                    "--tv-gain", os.path.join(work, "tv_gain.json"),
                    "--tv-loss", os.path.join(work, "tv_loss.json"),
                    "--out", tape, "--ts", "2026-11-06T08:31:02-04:00"],
                   capture_output=True, text=True, check=True)
    subprocess.run([sys.executable, SCRIPT, "digest",
                    "--tape", tape, "--out", digest,
                    "--meta", os.path.join(work, "meta.json"),
                    "--date", "2026-11-06", "--slot", "0830"],
                   capture_output=True, text=True, check=True)
    return tape, digest


def mutate(path, old, new, replace_all=False):
    """Replace `old` with `new` — and REFUSE if the file's bytes did not change.
    A mutation whose text does not actually change reports a false 'NOT CAUGHT'.

    The procedure embeds JSON inside a shell double-quoted string, so a target like
    '"sortBy":"x"' lives in the file as '\\"sortBy\\":\\"x\\"'. Both spellings are
    tried, and the replacement is escaped to match the form that was found."""
    s = open(path, encoding="utf-8").read()
    if old in s:
        s2 = s.replace(old, new) if replace_all else s.replace(old, new, 1)
    else:
        esc = old.replace('"', '\\"')
        if esc in s:
            s2 = (s.replace(esc, new.replace('"', '\\"')) if replace_all
                  else s.replace(esc, new.replace('"', '\\"'), 1))
        else:
            raise AssertionError(f"mutation target not found in {path}: {old[:60]!r}")
    if s2 == s:
        raise AssertionError("mutation did not change the file")
    open(path, "w", encoding="utf-8").write(s2)


def null_first_scanner_pct(path):
    """Strip the number from a SCANNER row — the row type that must always carry one."""
    lines = open(path, encoding="utf-8").read().split("\n")
    for i, ln in enumerate(lines):
        if '"src": "scanner"' in ln:
            lines[i] = re.sub(r'"pct": [0-9.\-]+', '"pct": null', ln, count=1)
            open(path, "w", encoding="utf-8").write("\n".join(lines))
            return
    raise AssertionError("no scanner row found to mutate")


def swap_first_two_table_rows(path):
    """Break the |%| ordering by swapping the first two body rows of the table."""
    lines = open(path, encoding="utf-8").read().split("\n")
    idx = [i for i, l in enumerate(lines)
           if l.strip().startswith("|") and "---" not in l and "Ticker" not in l]
    if len(idx) < 2:
        raise AssertionError("no table rows found to swap")
    i, j = idx[0], idx[1]
    lines[i], lines[j] = lines[j], lines[i]
    open(path, "w", encoding="utf-8").write("\n".join(lines))


def main():
    tmp = tempfile.mkdtemp(prefix="preopen-contract-")
    try:
        repo = make_repo(os.path.join(tmp, "repo"))
        tape, digest = build_conforming(tmp)

        print("conforming artifacts MUST pass:")
        rc, out = run_checker(repo, tape=tape, digest=digest)
        record("a conforming tape + digest passes the checker", True, rc, out)

        print("static breaches MUST be caught:")
        cases = [
            ("the gains sort is reverted to premarket_volume",
             "cloud-prompts/_shared/preopen-capture.md",
             '"sortBy":"premarket_change","sortOrder":"desc"',
             '"sortBy":"premarket_volume","sortOrder":"desc"', False),
            ("the losses sort is dropped",
             "cloud-prompts/_shared/preopen-capture.md",
             '"sortBy":"premarket_change","sortOrder":"asc"',
             '"sortBy":"premarket_volume","sortOrder":"asc"', False),
            ("the expected tape size is no longer documented",
             "cloud-prompts/_shared/preopen-capture.md",
             "The expected tape size is \u2248678 rows",
             "The expected tape size is unspecified", False),
            ("the deviation rule is deleted",
             "cloud-prompts/_shared/preopen-capture.md",
             "tape_size_deviation", "tape_size_note", True),
            ("the slot assertion is deleted",
             "cloud-prompts/_shared/preopen-capture.md",
             'grep -qx "$CP"', 'true # no assertion', False),
            ("the slot falls back to the wall clock",
             "cloud-prompts/_shared/preopen-capture.md",
             'CP_RAW=$(TZ=America/New_York date -d "@$((FIRE_MS/1000))" +%H%M)',
             'CP_RAW=$(TZ=America/New_York date +%H%M)', False),
            ("the skip marker is dropped",
             "cloud-prompts/_shared/preopen-capture.md",
             ".SKIPPED.md", ".SKIPPED", True),
            ("the halt state is published as a count",
             "cloud-prompts/_shared/preopen-capture.md",
             "halted: not measurable", "halted: 0", True),
            ("the digest step is dropped",
             "cloud-prompts/_shared/preopen-capture.md",
             "preopen_checkpoint.py digest", "echo digest", False),
            ("the script capability marker is dropped",
             "cloud-prompts/_shared/preopen-capture.md",
             "PREOPEN_CHECKPOINT_V1", "PREOPEN_V0", True),
            ("the prompt asks for a halt count again",
             "cloud-prompts/cron-prompts/92a-preopen-catalyst-capture-0830.md",
             "the scanner's halt state",
             "how many names the scanner flagged `halted`", False),
            ("the prompt stops mentioning the digest",
             "cloud-prompts/cron-prompts/92b-preopen-catalyst-capture-0950.md",
             "**digest** at", "**board** at", False),
            ("the script version is dropped from the fetch ladder",
             "cloud-prompts/_shared/preopen-capture.md",
             "CHECKPOINT_SCRIPT_VERSION: 2026-11-06.1", "CHECKPOINT_SCRIPT_VERSION: 2026-01-01", True),
            ("the tape schema grows a key",
             "cloud-prompts/_shared/preopen_checkpoint.py",
             '"ts", "src", "ticker", "name", "pct", "price", "cat", "why", "ref", "conf"',
             '"ts", "src", "ticker", "name", "pct", "price", "cat", "why", "ref", "conf", "extra"',
             False),
        ]
        for name, rel, old, new, rep in cases:
            r2 = make_repo(os.path.join(tmp, "m" + str(len(RESULTS))))
            mutate(os.path.join(r2, rel), old, new, replace_all=rep)
            rc, out = run_checker(r2, tape=tape, digest=digest)
            record(name, False, rc, out)

        print("artifact breaches MUST be caught:")
        arts = os.path.join(tmp, "arts")
        shutil.copytree(os.path.join(tmp, "preopen-feed"), arts)

        def art_case(name, mutate_fn, tape_p=tape, digest_p=digest):
            r2 = make_repo(os.path.join(tmp, "a" + str(len(RESULTS))))
            feed2 = os.path.join(tmp, "feed" + str(len(RESULTS)))
            shutil.copytree(os.path.join(tmp, "preopen-feed"), feed2)
            t2 = os.path.join(feed2, os.path.basename(tape_p))
            d2 = os.path.join(feed2, os.path.basename(digest_p))
            mutate_fn(t2, d2, feed2)
            rc, out = run_checker(r2, tape=t2, digest=d2)
            record(name, False, rc, out)

        art_case("the digest is missing", lambda t, d, f: os.remove(d))
        art_case("the digest table header is wrong",
                 lambda t, d, f: mutate(d, "| Ticker | % | Conf | Catalyst | When it broke |",
                                       "| Ticker | Pct | Conf | Catalyst | When |"))
        art_case("the digest drops the record count",
                 lambda t, d, f: mutate(d, "**records:**", "**rows:**"))
        art_case("the digest drops the measured cost",
                 lambda t, d, f: mutate(d, "$0.0476", "cost unknown"))
        art_case("the digest drops the unverified marker",
                 lambda t, d, f: mutate(d, "\u26a0 unverified", "unverified"))
        art_case("the digest rows are out of order",
                 lambda t, d, f: swap_first_two_table_rows(d))
        art_case("the tape grows an eleventh key",
                 lambda t, d, f: mutate(t, '"conf": "low"', '"conf": "low", "x": 1'))
        art_case("the tape duplicates a ticker",
                 lambda t, d, f: open(t, "a", encoding="utf-8").write(
                     open(t, encoding="utf-8").readlines()[0]))
        art_case("a scanner row loses its number but keeps its confidence",
                 lambda t, d, f: null_first_scanner_pct(t))

        print("a 120-row tape MUST be flagged as a deviation:")
        small = os.path.join(tmp, "small")
        os.makedirs(small, exist_ok=True)
        tape_s, digest_s = build_conforming(small, n_rows=120)
        r2 = make_repo(os.path.join(tmp, "smallrepo"))
        # the banner is present in the generated digest -> the checker must PASS it
        rc, out = run_checker(r2, tape=tape_s, digest=digest_s)
        record("a 120-row tape with the deviation banner passes", True, rc, out)
        # strip the banner -> the checker must FAIL
        r3 = make_repo(os.path.join(tmp, "smallrepo2"))
        mutate(digest_s, "DEVIATION", "no banner")
        rc, out = run_checker(r3, tape=tape_s, digest=digest_s)
        record("a 120-row tape WITHOUT the deviation banner is caught", False, rc, out)

        print("a fail-closed checkpoint MUST leave a trail:")
        skipdir = os.path.join(tmp, "skip")
        os.makedirs(skipdir, exist_ok=True)
        marker = os.path.join(skipdir, "2026-11-06-0830.SKIPPED.md")
        subprocess.run([sys.executable, SCRIPT, "skipped", "--out", marker,
                        "--reason", "XAI_API_KEY is unset", "--date", "2026-11-06",
                        "--slot", "0830"], capture_output=True, text=True, check=True)
        r4 = make_repo(os.path.join(tmp, "skiprepo"))
        rc, out = run_checker(r4, skipped=marker)
        record("a conforming skip marker passes", True, rc, out)

        m2 = os.path.join(skipdir, "b.SKIPPED.md")
        shutil.copy(marker, m2)
        mutate(m2, "- **Reason:** XAI_API_KEY is unset", "- **Reason:**")
        rc, out = run_checker(r4, skipped=m2)
        record("a skip marker without a reason is caught", False, rc, out)

        m3 = os.path.join(skipdir, "c.SKIPPED.md")
        shutil.copy(marker, m3)
        open(os.path.join(skipdir, "c.jsonl"), "w").write("{}\n")
        rc, out = run_checker(r4, skipped=m3)
        record("a skip marker beside a JSONL tape is caught", False, rc, out)

        print()
        failed = [r for r in RESULTS if not r[1]]
        print(f"{len(RESULTS) - len(failed)}/{len(RESULTS)} contract cases behaved correctly")
        if failed:
            print("FAILED:")
            for name, ok, rc, out in failed:
                print(f"  - {name}")
            return 1
        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
